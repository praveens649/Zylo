import { useState } from "react";
import { Check, ChevronRight, Flame, Loader2, RefreshCw, Search } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Input } from "@/components/ui/input";
import { PhoneNumber } from "@/api/numbers.api";

interface StepNumberSelectionProps {
  numbers: PhoneNumber[];
  isLoading: boolean;
  selectedNumber: PhoneNumber | null;
  isReserving: boolean;
  onSelectNumber: (num: PhoneNumber) => void;
  onGenerateNumbers: () => void;
  onBack: () => void;
  onNext: () => void;
  onSearchChange: (search: string) => void;
  filter: "ALL" | "STANDARD" | "PREMIUM";
  onFilterChange: (filter: "ALL" | "STANDARD" | "PREMIUM") => void;
}

export function StepNumberSelection({
  numbers,
  isLoading,
  selectedNumber,
  isReserving,
  onSelectNumber,
  onGenerateNumbers,
  onBack,
  onNext,
  onSearchChange,
  filter,
  onFilterChange,
}: StepNumberSelectionProps) {
  const [searchInput, setSearchInput] = useState("");

  const handleSearchInput = (val: string) => {
    setSearchInput(val);
    onSearchChange(val);
  };

  return (
    <div className="space-y-6 animate-fade-up">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold font-display text-foreground">
            Step 3: Select Your Mobile Number
          </h1>
          <p className="text-sm text-muted-foreground mt-1">
            Choose a standard or VIP vanity number generated by the Zylo numbering engine.
          </p>
        </div>

        <Button
          variant="outline"
          size="sm"
          onClick={onGenerateNumbers}
          className="flex items-center gap-2 self-start sm:self-auto"
        >
          <RefreshCw className="h-3.5 w-3.5" />
          Generate New Pool
        </Button>
      </div>

      {/* Filter & Search Bar */}
      <div className="flex flex-col sm:flex-row gap-3">
        <div className="relative flex-1">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
          <Input
            placeholder="Search preferred digits (e.g. 786, 9999)..."
            className="pl-9"
            value={searchInput}
            onChange={(e) => handleSearchInput(e.target.value)}
          />
        </div>

        <div className="flex gap-2">
          <Button
            variant={filter === "ALL" ? "default" : "outline"}
            size="sm"
            onClick={() => onFilterChange("ALL")}
          >
            All
          </Button>
          <Button
            variant={filter === "STANDARD" ? "default" : "outline"}
            size="sm"
            onClick={() => onFilterChange("STANDARD")}
          >
            Standard (₹0)
          </Button>
          <Button
            variant={filter === "PREMIUM" ? "default" : "outline"}
            size="sm"
            onClick={() => onFilterChange("PREMIUM")}
          >
            <Flame className="h-3.5 w-3.5 mr-1 text-amber-500" />
            VIP Premium
          </Button>
        </div>
      </div>

      {/* Numbers Grid */}
      {isLoading ? (
        <div className="py-12 flex justify-center">
          <Loader2 className="h-8 w-8 animate-spin text-primary" />
        </div>
      ) : numbers && numbers.length > 0 ? (
        <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-3">
          {numbers.map((item) => {
            const isSelected = selectedNumber?.id === item.id;
            const isPremium = item.type === "PREMIUM";

            return (
              <div
                key={item.id}
                onClick={() => onSelectNumber(item)}
                className={`cursor-pointer rounded-xl border p-4 transition-all relative ${
                  isSelected
                    ? "border-primary bg-primary/10 ring-2 ring-primary shadow-sm"
                    : "border-border bg-card hover:border-primary/50"
                }`}
              >
                <div className="flex items-center justify-between">
                  <span className="font-mono text-base font-bold tracking-wider text-foreground">
                    {item.number}
                  </span>
                  {isSelected && (
                    <div className="flex h-5 w-5 items-center justify-center rounded-full bg-primary text-primary-foreground">
                      <Check className="h-3 w-3" />
                    </div>
                  )}
                </div>

                <div className="mt-3 flex items-center justify-between text-xs">
                  {isPremium ? (
                    <Badge className="bg-amber-500/10 text-amber-600 border-amber-500/20 font-semibold">
                      VIP • ₹{item.price}
                    </Badge>
                  ) : (
                    <Badge variant="secondary" className="text-muted-foreground">
                      Standard • FREE
                    </Badge>
                  )}

                  <span className="text-[11px] text-muted-foreground">
                    {item.prefix ? `Series ${item.prefix}` : "Personal"}
                  </span>
                </div>
              </div>
            );
          })}
        </div>
      ) : (
        <div className="rounded-xl border border-dashed border-border p-10 text-center">
          <p className="text-sm text-muted-foreground">
            No available numbers matching your search filter.
          </p>
          <Button
            className="mt-4 font-semibold"
            size="sm"
            onClick={onGenerateNumbers}
          >
            Generate 10 Numbers Now
          </Button>
        </div>
      )}

      {/* Selected Number Hold Banner */}
      {selectedNumber && (
        <div className="rounded-xl border border-primary/30 bg-primary/5 p-4 flex items-center justify-between">
          <div>
            <span className="text-xs text-muted-foreground font-medium">
              Selected Mobile Number:
            </span>
            <div className="font-mono text-lg font-bold text-foreground">
              {selectedNumber.number}
            </div>
          </div>
          <Badge variant="secondary" className="text-xs text-emerald-600">
            Reserved for 15 minutes
          </Badge>
        </div>
      )}

      <div className="flex justify-between items-center pt-4">
        <Button variant="outline" onClick={onBack}>
          Back
        </Button>

        <Button
          size="lg"
          className="font-semibold px-6"
          disabled={!selectedNumber || isReserving}
          onClick={onNext}
        >
          Continue to Plan Selection
          <ChevronRight className="h-4 w-4 ml-2" />
        </Button>
      </div>
    </div>
  );
}
